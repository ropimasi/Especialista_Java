public class ToUpperCase {

	public static void main(String[] args) {
		
		String nome = "Pedro";
		nome.toUpperCase();
		System.out.println(nome);
		
		String nomeEmMaiusculo = nome.toUpperCase();
		System.out.println(nomeEmMaiusculo);
		System.out.println(nome);
		
		

	}

}
