public class Replace {

	public static void main(String[] args) {
		
		String nome = "Pedro da Silva da Costa de Oliveira";
		System.out.println(nome);
		System.out.println(nome.replace("a", "@"));
		System.out.println(nome.replace(" da ", " "));
		
		
	}
	
}
